const STORAGE_KEY_THEME = "fingerspot-theme";
const STORAGE_KEY_LANG = "fingerspot-lang";

export function ThemeLanguageProvider({ children }: { children: ReactNode }) {
  const [theme, setThemeState] = useState<Theme>("light");
  const [lang, setLangState] = useState<Lang>("id");
  const [mounted, setMounted] = useState(false);

  useEffect(() => {
    const savedTheme = localStorage.getItem(STORAGE_KEY_THEME) as Theme | null;
    const savedLang = localStorage.getItem(STORAGE_KEY_LANG) as Lang | null;
    if (savedTheme) setThemeState(savedTheme);
    if (savedLang) setLangState(savedLang);
    setMounted(true);
  }, []);

  useEffect(() => {
    if (!mounted) return;
    document.documentElement.classList.toggle("dark", theme === "dark");
    localStorage.setItem(STORAGE_KEY_THEME, theme);
  }, [theme, mounted]);

  useEffect(() => {
    if (!mounted) return;
    localStorage.setItem(STORAGE_KEY_LANG, lang);
  }, [lang, mounted]);

  const setTheme = useCallback((t: Theme) => setThemeState(t), []);
  const setLang = useCallback((l: Lang) => setLangState(l), []);

  const t = useCallback(
    (key: string): string => {
      return translations[lang]?.[key] || translations.id?.[key] || key;
    },
    [lang]
  );

  if (!mounted) {
    return <>{children}</>;
  }

  return (
    <ThemeLanguageContext.Provider value={{ theme, lang, setTheme, setLang, t }}>
      {children}
    </ThemeLanguageContext.Provider>
  );
}
